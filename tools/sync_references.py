#!/usr/bin/env python3
"""Regenerate the skill's reference tables from an upstream napkin-math checkout.

    python tools/sync_references.py <path-to-napkin-math-checkout>          # write
    python tools/sync_references.py <path-to-napkin-math-checkout> --check  # exit 1 if stale

The upstream README.md is the single source of truth for the numbers. This script
copies its "Numbers", "Cost Numbers" and "Compression Ratios" sections verbatim into
skills/napkin-math/references/, adds a provenance header (commit and date), and
rewrites relative links to absolute GitHub links. Never hand-edit the generated
files: put your own measurements in references/local.md instead.
"""

import argparse
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
REFS = REPO / "skills" / "napkin-math" / "references"
UPSTREAM_URL = "https://github.com/sirupsen/napkin-math"

# README section heading -> (output file, title, one-line purpose)
SECTIONS = {
    "Numbers": (
        "numbers.md",
        "Latency and throughput",
        "One latency and one throughput per operation: CPU, memory, caches, SSD, HDD, "
        "network disks, network, blob storage, services, GPUs. Read the footnotes and the "
        "prose under the table: they hold the caveats that decide most estimates.",
    ),
    "Cost Numbers": (
        "costs.md",
        "Cloud costs",
        "Unit prices (compute, memory, storage, network, CDN, logs), blob request fees, "
        "instance shapes per vCPU, and the derived $ per TiB read for each way of reading data.",
    ),
    "Compression Ratios": (
        "compression.md",
        "Compression ratios",
        "General-purpose codecs by data type, columnar encodings, and search-index sizes "
        "as a fraction of the indexed text.",
    ),
}


def upstream_commit(checkout: Path, override: str | None) -> tuple[str, str]:
    if override:
        return override, "unknown date"
    try:
        sha = subprocess.check_output(
            ["git", "-C", str(checkout), "rev-parse", "HEAD"], text=True
        ).strip()
        date = subprocess.check_output(
            ["git", "-C", str(checkout), "log", "-1", "--format=%cs"], text=True
        ).strip()
        dirty = subprocess.check_output(
            ["git", "-C", str(checkout), "status", "--porcelain", "README.md"], text=True
        ).strip()
        if dirty:
            sha += "+dirty"
        return sha, date
    except (OSError, subprocess.CalledProcessError):
        sys.exit("sync: not a git checkout; pass --commit <sha> to record the source")


def split_sections(readme: str) -> dict[str, str]:
    """Map each '## Heading' to the text under it, up to the next '## '."""
    parts = re.split(r"^## +(.+?)\s*$", readme, flags=re.M)
    return {parts[i]: parts[i + 1].strip("\n") for i in range(1, len(parts), 2)}


def absolutize_links(text: str, sha: str) -> str:
    ref = sha.removesuffix("+dirty")

    def fix(m: re.Match) -> str:
        label, target = m.group(1), m.group(2)
        if re.match(r"^[a-z]+:|^#", target):
            return m.group(0)
        return f"[{label}]({UPSTREAM_URL}/blob/{ref}/{target})"

    return re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", fix, text)


def render(heading: str, body: str, sha: str, date: str) -> str:
    _, title, purpose = SECTIONS[heading]
    short = sha[:7] + ("+dirty" if sha.endswith("+dirty") else "")
    return (
        f"<!-- Generated by tools/sync_references.py from {UPSTREAM_URL} README.md, "
        f'section "{heading}", commit {sha}. Do not edit: rerun the script, and put '
        f"your own measurements in local.md. -->\n\n"
        f"# {title}\n\n"
        f"{purpose}\n\n"
        f"Source: [sirupsen/napkin-math]({UPSTREAM_URL}) README at `{short}` ({date}), "
        f"MIT License, Copyright (c) 2019 Simon Eskildsen. Numbers are rounded for "
        f"memorization: trust the order of magnitude more than the digit.\n\n"
        f"{absolutize_links(body, sha)}\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("upstream", type=Path, help="path to a napkin-math checkout")
    ap.add_argument("--check", action="store_true", help="exit 1 if any generated file is stale")
    ap.add_argument("--commit", help="source commit to record when the checkout isn't a git repo")
    args = ap.parse_args()

    readme_path = args.upstream / "README.md"
    if not readme_path.is_file():
        sys.exit(f"sync: {readme_path} not found")
    sections = split_sections(readme_path.read_text(encoding="utf-8"))
    missing = [h for h in SECTIONS if h not in sections]
    if missing:
        sys.exit(f"sync: upstream README has no section(s) {missing}; found {list(sections)}")

    sha, date = upstream_commit(args.upstream, args.commit)
    stale = []
    for heading, (filename, _, _) in SECTIONS.items():
        out = REFS / filename
        text = render(heading, sections[heading], sha, date)
        current = out.read_text(encoding="utf-8") if out.exists() else None
        if current == text:
            continue
        stale.append(filename)
        if not args.check:
            out.write_text(text, encoding="utf-8", newline="\n")

    if args.check:
        if stale:
            print(f"sync: stale against {sha[:7]}: {', '.join(stale)}", file=sys.stderr)
            return 1
        print(f"sync: up to date with {sha[:7]}")
        return 0
    print(f"sync: wrote {', '.join(stale) or 'nothing (already up to date)'} from {sha[:7]} ({date})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
